    @bedrock_breaker
    @traceable(name="bedrock_converse_with_tools")
    def converse_with_tools(self, messages, system_prompt, tools, max_retries=3):
        """Bedrock Converse API with tool definitions for structured output."""
        for attempt in range(max_retries):
            try:
                response = self.bedrock_client.converse(
                    modelId=self.model_id,
                    system=[{"text": system_prompt}],
                    messages=messages,
                    toolConfig={"tools": tools},
                    inferenceConfig={"maxTokens": self.max_tokens, "temperature": self.temperature},
                )
                self._log_usage(response, "converse_with_tools")
                return response
            except ClientError as e:
                error_code = e.response.get('Error', {}).get('Code', '')
                if error_code in ('ThrottlingException', 'ServiceUnavailableException', 'ModelTimeoutException') and attempt < max_retries - 1:
                    wait = 2 ** attempt
                    self.log.warning(f"Bedrock converse throttled, retrying in {wait}s (attempt {attempt + 1})")
                    time.sleep(wait)
                    continue
                raise RuntimeError(f"Bedrock converse failed after {attempt + 1} attempts: {e}") from e
            except Exception as e:
                raise RuntimeError(f"Bedrock converse failed: {e}") from e
        raise RuntimeError("Bedrock converse failed after retries")

    @bedrock_breaker
    @traceable(name="bedrock_stream_messages")
    def stream_messages(self, messages: list, system_prompt: str = None):
        """Stream response tokens from a full message history.

        Yields individual text chunks as they arrive from the model.
        Uses invoke_model_with_response_stream for real-time token delivery.
        """
        native_request = {
            "anthropic_version": "bedrock-2023-05-31",
            "max_tokens": self.max_tokens,
            "temperature": self.temperature,
            "messages": messages,
        }
        if system_prompt:
            native_request["system"] = system_prompt

        request = json.dumps(native_request)

        for attempt in range(3):
            try:
                response = self.bedrock_client.invoke_model_with_response_stream(
                    modelId=self.model_id, body=request)
                break
            except ClientError as e:
                error_code = e.response.get('Error', {}).get('Code', '')
                if error_code in ('ThrottlingException', 'ServiceUnavailableException', 'ModelTimeoutException') and attempt < 2:
                    wait = 2 ** attempt
                    self.log.warning(f"Bedrock stream throttled/timeout, retrying in {wait}s (attempt {attempt + 1})")
                    time.sleep(wait)
                    continue
                raise RuntimeError(f"Bedrock stream failed after {attempt + 1} attempts: {e}") from e
            except Exception as e:
                raise RuntimeError(f"Bedrock stream failed: {e}") from e

        stream = response.get("body")
        if not stream:
            self.log.warning("Bedrock stream returned no body")
            return

        yielded = False
        for event in stream:
            chunk = event.get("chunk")
            if chunk:
                payload = json.loads(chunk["bytes"].decode())
                if payload.get("type") == "content_block_delta":
                    delta = payload.get("delta", {})
                    if delta.get("type") == "text_delta":
                        yielded = True
                        yield delta["text"]

        if not yielded:
            self.log.warning("Bedrock stream completed without yielding any text tokens")

    @bedrock_breaker
    @traceable(name="bedrock_predict_messages")
    def predict_messages(self, messages: list, system_prompt: str = None) -> str:
        """Generate response from a full message history.

        Args:
            messages (list): List of message dicts with 'role' and 'content'.
            system_prompt (str, optional): System prompt to guide the model.

        Returns:
            str: The model's response text.
        """
        native_request = {
            "anthropic_version": "bedrock-2023-05-31",
            "max_tokens": self.max_tokens,
            "temperature": self.temperature,
            "messages": messages,
        }
        if system_prompt:
            native_request["system"] = system_prompt

        request = json.dumps(native_request)

        for attempt in range(3):
            try:
                response = self.bedrock_client.invoke_model(
                    modelId=self.model_id, body=request)
                break
            except ClientError as e:
                error_code = e.response.get('Error', {}).get('Code', '')
                if error_code in ('ThrottlingException', 'ServiceUnavailableException', 'ModelTimeoutException') and attempt < 2:
                    wait = 2 ** attempt
                    self.log.warning(f"Bedrock throttled/timeout, retrying in {wait}s (attempt {attempt + 1})")
                    time.sleep(wait)
                    continue
                raise RuntimeError(f"Bedrock failed after {attempt + 1} attempts: {e}") from e
            except Exception as e:
                raise RuntimeError(f"Bedrock failed: {e}") from e

        model_response = json.loads(response["body"].read())
        self._log_usage(model_response, "predict_messages")
        blocks = model_response.get("content", [])
        return " ".join(
            b["text"] for b in blocks
            if b.get("type") == "text" and isinstance(b.get("text"), str)
        )
